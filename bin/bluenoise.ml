(* bluenoise — the void-and-cluster threshold-map generator (Ulichney 1993),
   host-side tooling for the dither kernel (AGENT.md §5).

   Emits a 64x64 blue-noise threshold table as C source on stdout — the
   __dg_bn64 array baked into libc/dither.c. Deterministic by construction
   (fixed LCG seed, first-index tie-breaks), so the table regenerates
   byte-identically: the array in dither.c IS this program's output, and the
   provenance line there names the parameters.

   Method: a binary "prototype" pattern (~10% ones) is relaxed until the
   tightest cluster and the largest void coincide (swap-until-stable); ranks
   then assign by removing tightest clusters downward (ranks m-1..0) and
   filling largest voids upward (ranks m..4095), with cluster/void measured
   by a toroidal gaussian energy field. Rank r maps to threshold
   1 + r*253/4095 — the 1..254 range that keeps the kernel's endpoint
   guarantee: luminance 0 never fires, 255 always does.

   Usage: dune exec bin/bluenoise.exe [-- -sigma S] [-- -pgm P]
          (C array on stdout; -sigma defaults to the shipping 1.5; -pgm also writes a
          50%-mask preview PGM) *)

let n = 64
let cells = n * n

let find_arg name default parse =
  let rec go = function
    | a :: v :: _ when a = name -> parse v
    | _ :: rest -> go rest
    | [] -> default
  in
  go (Array.to_list Sys.argv)
;;

let sigma = find_arg "-sigma" 1.5 float_of_string

let k_r =
  15 (* kernel cutoff: exp(-15^2 / (2*sigma^2)) is negligible for any sane sigma *)
;;

let ones_initial = cells / 10
let seed = 0x1234_5678

(* the gaussian kernel, toroidal application *)
let kernel =
  Array.init
    ((2 * k_r) + 1)
    (fun i ->
       Array.init
         ((2 * k_r) + 1)
         (fun j ->
            let dy = float_of_int (i - k_r)
            and dx = float_of_int (j - k_r) in
            exp (-.((dx *. dx) +. (dy *. dy)) /. (2.0 *. sigma *. sigma))))
;;

let pat = Array.make cells false
let energy = Array.make cells 0.0
let idx x y = (y land (n - 1) * n) + (x land (n - 1))

let splat c s =
  let cy = c / n
  and cx = c mod n in
  for i = 0 to 2 * k_r do
    for j = 0 to 2 * k_r do
      let e = idx (cx + j - k_r) (cy + i - k_r) in
      energy.(e) <- energy.(e) +. (s *. kernel.(i).(j))
    done
  done
;;

let insert c =
  pat.(c) <- true;
  splat c 1.0
;;

let remove c =
  pat.(c) <- false;
  splat c (-1.0)
;;

(* first-index tie-breaks keep every run identical *)
let tightest_cluster () =
  let best = ref (-1)
  and be = ref neg_infinity in
  for c = 0 to cells - 1 do
    if pat.(c) && energy.(c) > !be
    then (
      be := energy.(c);
      best := c)
  done;
  !best
;;

let largest_void () =
  let best = ref (-1)
  and be = ref infinity in
  for c = 0 to cells - 1 do
    if (not pat.(c)) && energy.(c) < !be
    then (
      be := energy.(c);
      best := c)
  done;
  !best
;;

let () =
  (* initial pattern: [ones_initial] distinct cells from a fixed LCG *)
  let state = ref seed in
  let lcg () =
    state := ((!state * 1103515245) + 12345) land 0x3FFF_FFFF;
    !state mod cells
  in
  let placed = ref 0 in
  while !placed < ones_initial do
    let c = lcg () in
    if not pat.(c)
    then (
      insert c;
      incr placed)
  done;
  (* relax: move the tightest cluster into the largest void until they meet *)
  let rec relax () =
    let t = tightest_cluster () in
    remove t;
    let v = largest_void () in
    insert v;
    if v <> t then relax ()
  in
  relax ();
  let proto = Array.copy pat in
  let ranks = Array.make cells 0 in
  (* phase 1: peel tightest clusters off the prototype, ranks m-1 .. 0 *)
  for r = ones_initial - 1 downto 0 do
    let t = tightest_cluster () in
    remove t;
    ranks.(t) <- r
  done;
  (* restore the prototype and its energy field *)
  Array.blit proto 0 pat 0 cells;
  Array.fill energy 0 cells 0.0;
  Array.iteri (fun c one -> if one then splat c 1.0) proto;
  (* phases 2+3: fill largest voids, ranks m .. cells-1 *)
  for r = ones_initial to cells - 1 do
    let v = largest_void () in
    insert v;
    ranks.(v) <- r
  done;
  let thr = Array.map (fun r -> 1 + (r * 253 / (cells - 1))) ranks in
  (* optional preview: the 50% mask (white where threshold < 128) *)
  (match find_arg "-pgm" None (fun p -> Some p) with
   | Some path ->
     Out_channel.with_open_bin path (fun oc ->
       Printf.fprintf oc "P5\n%d %d\n255\n" n n;
       Array.iter
         (fun t -> Out_channel.output_char oc (if t < 128 then '\255' else '\000'))
         thr)
   | None -> ());
  Printf.printf
    "/* 64x64 void-and-cluster blue noise — generated by bin/bluenoise.ml\n\
    \ * (seed 0x%08X, sigma %.1f, thresholds 1..254; regenerate:\n\
    \ * dune exec bin/bluenoise.exe). Row-major, indexed [64*(y&63) + (x&63)]. */\n\
     static const unsigned char __dg_bn64[64 * 64] = {\n"
    seed
    sigma;
  for row = 0 to (cells / 16) - 1 do
    print_string "    ";
    for k = 0 to 15 do
      Printf.printf "%d,%s" thr.((row * 16) + k) (if k = 15 then "" else " ")
    done;
    print_newline ()
  done;
  print_string "};\n"
;;
